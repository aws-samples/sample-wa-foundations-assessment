// Five horizontal steps do not fit a phone-width viewport.
const NARROW_QUERY = "(max-width: 688px)";

function useIsNarrow() {
  const query = useMemo(
    () =>
      typeof window !== "undefined" && window.matchMedia
        ? window.matchMedia(NARROW_QUERY)
        : null,
    [],
  );
  const [isNarrow, setIsNarrow] = useState(query ? query.matches : false);
  useEffect(() => {
    if (!query) {
      return undefined;
    }
    const onChange = (event) => setIsNarrow(event.matches);
    query.addEventListener("change", onChange);
    return () => query.removeEventListener("change", onChange);
  }, [query]);
  return isNarrow;
}

function MaturityProgress({ maturity }) {
  const levels = maturity.scoring_model ? maturity.scoring_model.levels : [];
  const isNarrow = useIsNarrow();
  return (
    <Container header={<Header variant="h2">Maturity Progress</Header>}>
      <SpaceBetween size="l">
        {levels.length > 0 && (
          <Steps
            orientation={isNarrow ? "vertical" : "horizontal"}
            ariaLabel="Maturity level progression"
            steps={levels.map((level) => {
              const state = LEVEL_STATE[level.state] || LEVEL_STATE.locked;
              return {
                status: state.type,
                statusIconAriaLabel: state.label,
                header: `Level ${level.level} — ${level.name}`,
                details: (
                  <SpaceBetween size="xxs">
                    <Box fontWeight="bold">{state.label}</Box>
                    <Box color="text-body-secondary">
                      {level.criteria_count
                        ? `${level.complete_count}/${level.criteria_count} criteria`
                        : "Baseline"}
                    </Box>
                  </SpaceBetween>
                ),
              };
            })}
          />
        )}
        {maturity.next_level ? (
          <SpaceBetween size="m">
            <ProgressBar
              value={maturity.next_level_progress}
              label={`Progress toward Level ${maturity.next_level}`}
            />
            {maturity.next_level_checks_needed &&
              maturity.next_level_checks_needed.length > 0 && (
                <SpaceBetween size="xs">
                  <Header variant="h3">Next steps (highest impact first)</Header>
                  <List
                    tagOverride="ol"
                    ariaLabel="Next steps"
                    items={maturity.next_level_checks_needed.slice(0, 5)}
                    renderItem={(name) => ({ id: name, content: name })}
                  />
                </SpaceBetween>
              )}
          </SpaceBetween>
        ) : (
          <Alert type="success">All Phase 1 criteria met.</Alert>
        )}
      </SpaceBetween>
    </Container>
  );
}

function CapabilityCoverage({ axes }) {
  const gaps = axes.filter((axis) => axis.check_count === 0);
  const notAssessed = axes.filter(
    (axis) => axis.check_count > 0 && axis.assessed_count === 0,
  );
  return (
    <Container
      header={
        <Header
          variant="h2"
          description="Percentage of assessed mapped checks that are complete for each WA Foundations capability. Checks not run in this account mode are excluded."
        >
          Capability Coverage (WA Foundations)
        </Header>
      }
    >
      <SpaceBetween size="m">
        <BarChart
          ariaLabel="WA Foundations capability coverage"
          horizontalBars
          hideFilter
          hideLegend
          height={320}
          xScaleType="categorical"
          yDomain={[0, 100]}
          xTitle="Capability"
          yTitle="Coverage (%)"
          series={[
            {
              title: "Coverage",
              type: "bar",
              data: axes.map((axis) => ({ x: axis.name, y: axis.score })),
              valueFormatter: (value) => `${value}%`,
            },
          ]}
        />
        {gaps.length > 0 && (
          <Box color="text-body-secondary" fontSize="body-s">
            {gaps.map((axis) => axis.name).join(", ")}: no Phase 1 checks are
            mapped to this capability yet, so it reports 0% coverage.
          </Box>
        )}
        {notAssessed.length > 0 && (
          <Box color="text-body-secondary" fontSize="body-s">
            {notAssessed.map((axis) => axis.name).join(", ")}: not assessed in
            this account mode, so 0% does not indicate a gap.
          </Box>
        )}
      </SpaceBetween>
    </Container>
  );
}

