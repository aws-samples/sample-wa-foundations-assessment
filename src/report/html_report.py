def _assessed_axis_checks(checks):
    """Return, per capability axis, the mapped check names this run assessed."""
    assessed = {c.get("check") for c in checks}
    return {
        axis_name: [name for name in check_names if name in assessed]
        for axis_name, check_names in CAPABILITY_AXES.items()
    }


def _calculate_axis_scores(checks):
    """Calculate percentage score per capability axis.

    Scores use only the mapped checks this run assessed, so checks skipped in
    limited mode are not counted as gaps.
    """
    complete = {c.get("check") for c in checks if c.get("status") == "complete"}
    return {
        axis_name: (
            round(sum(1 for name in names if name in complete) / len(names) * 100)
            if names
            else 0
        )
        for axis_name, names in _assessed_axis_checks(checks).items()
    }


@cache
def _load_asset(name):
    """Return a prebuilt report UI asset.

    The assets are generated by ``npm run build`` in ``report-ui/``. The build
    escapes closing ``</script`` and ``</style`` sequences, so they are trusted
    repository code that the template inlines with ``safe``.
    """
    return (ASSETS_DIR / name).read_text(encoding="utf-8")


def _org_map_rows(org_map):
    """Return display rows for the organization map, with policy labels.

    ``key`` is a stable row identity for the report table, so the UI does not
    have to construct one.
    """
    return [
        dict(
            row,
            key=f"{row.get('kind', '')}:{row.get('id', '')}",
            policies=labelled_policies(row.get("policies")),
        )
        for row in flatten_rows(org_map)
    ]


def _org_map_summary(org_map):
    """Return only the map-level fields the report UI reads.

    The complete tree stays in ``wafa-raw.json``. Embedding it here as well
    roughly doubles the inline JSON for data the UI never reads: it renders the
    flattened rows plus these few summary fields.

    ``depthTruncatedPaths`` replaces the ``depthTruncated`` flag for display.
    An empty list means the walk completed, and a non-empty one names the OUs
    where it stopped, so the summary locates the gap instead of restating a
    condition that each affected row already carries as a note.
    """
    if not org_map:
        return None
    return {
        "organizationId": org_map.get("organizationId", ""),
        "totals": org_map.get("totals") or {},
        "policyLookupErrors": org_map.get("policyLookupErrors") or [],
        "depthTruncatedPaths": org_map.get("depthTruncatedPaths") or [],
    }


def _build_report_data(
    checks,
    maturity,
    delegated_admins,
    account_info,
    delegated_admins_error=None,
    org_map=None,
    org_map_error=None,
):
    """Assemble the JSON payload rendered by the Cloudscape report UI."""
    axis_scores = _calculate_axis_scores(checks)
    assessed_axis_checks = _assessed_axis_checks(checks)
    total = len(checks)
    complete = sum(1 for c in checks if c["status"] == "complete")
    incomplete = sum(1 for c in checks if c["status"] == "incomplete")
    errors = sum(1 for c in checks if c["status"] == "error")
    return {
        "checks": checks,
        "maturity": maturity,
        "delegated_administrators": delegated_admins,
        "delegated_administrators_error": delegated_admins_error,
        # Map-level fields only. The full tree is in wafa-raw.json as
        # organization_map; the UI renders organization_map_rows.
        "organization_map_summary": _org_map_summary(org_map),
        "organization_map_error": org_map_error,
        # Flattened in Python so the UI renders structured data instead of
        # re-deriving the hierarchy and policy labels in JavaScript, which
        # would let the CSV and the HTML from one run disagree.
        "organization_map_rows": _org_map_rows(org_map),
        # Labels for the guardrail policy types that are not enabled, so the
        # UI never derives a label itself.
        "organization_map_not_enabled_labels": [
            policy_type_label(policy_type)
            for policy_type in (org_map or {}).get("policyTypesNotEnabled") or []
        ],
        "account_info": account_info,
        "axis_scores": [
            {
                "name": name,
                "score": score,
                "check_count": len(CAPABILITY_AXES[name]),
                "assessed_count": len(assessed_axis_checks[name]),
            }
            for name, score in axis_scores.items()
        ],
        "summary": {
            "total": total,
            "complete": complete,
            "incomplete": incomplete,
            "errors": errors,
            "pct": round(complete / total * 100) if total > 0 else 0,
        },
    }


def generate_html(
    checks,
    maturity,
    delegated_admins=None,
    account_info=None,
    delegated_admins_error=None,
    org_map=None,
    org_map_error=None,
):
    """Generate the interactive HTML report.

    Args:
        checks: list of check result dicts
        maturity: maturity level result dict
        delegated_admins: list of delegated admin dicts (optional)
        account_info: account info dict (optional)
        delegated_admins_error: why delegated admins could not be fully
            listed (optional)
        org_map: organization and OU account map dict (optional, FR-12)
        org_map_error: why the organization map could not be built (optional)

    Returns:
        str: Complete HTML document as string
    """
    if delegated_admins is None:
        delegated_admins = []
    if account_info is None:
        account_info = {}

    # The report is a standalone HTML document, so use a sandboxed environment
    # with autoescaping instead of relying on a web framework's renderer.
    env = SandboxedEnvironment(
        loader=BaseLoader(),
        autoescape=select_autoescape(default_for_string=True, default=True),
    )
    # Match the raw JSON export: non-JSON AWS values such as datetimes are
    # rendered as strings instead of failing the report.
    env.policies["json.dumps_kwargs"] = {"sort_keys": True, "default": str}
    template = env.from_string(HTML_TEMPLATE)
    rendered = template.render(
        # tojson escapes <, >, &, and ' as Unicode escapes, so AWS-provided
        # text cannot break out of the JSON data element.
        report_data=_build_report_data(
            checks,
            maturity,
            delegated_admins,
            account_info,
            delegated_admins_error,
            org_map,
            org_map_error,
        ),
        report_css=_load_asset("report-ui.css"),
        report_js=_load_asset("report-ui.js"),
    )
    return "\n".join(line.rstrip() for line in rendered.splitlines()) + "\n"


HTML_TEMPLATE = """<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="UTF-8">
<meta name="viewport" content="width=device-width, initial-scale=1.0">
<title>WA-Foundations Report</title>
<style>
{{ report_css | safe }}
</style>
</head>
<body>
<noscript>
    <h1>Well-Architected Foundations Assessment Report</h1>
    <p>This report requires JavaScript. The same results are available in the
    CSV and JSON files generated with this report.</p>
</noscript>
<div id="wafa-report-root"></div>
<script type="application/json" id="wafa-report-data">{{ report_data | tojson }}</script>
<script>
{{ report_js | safe }}
</script>
</body>
</html>"""
