"""HTML Report Generation (FR-10.1).

Generates a self-contained HTML report built from Cloudscape Design System
components. The React UI is compiled from ``report-ui/`` into the static
bundle under ``assets/`` and inlined into every report together with the
assessment data, so the report renders without any network access.

The report contains:
- Maturity level score and progress
- Capability coverage bar chart over the 7 WA Foundations capability axes
- Assessment overview
- Check results table with filtering
- Delegated administrators table
- Organization and OU account map with attached policies (FR-12)
- Light/dark mode toggle
"""

